  # Задача №18 (задача с перчиком). Четные цифры 2️⃣🌶️. На вход программе подаётся натуральное число n. Напишите программу, которая выводит для каждой четной цифры данного числа текст в следующем формате:
  # <i>-я четная цифра равна <digit>
  # где <i> – номер четной цифры (начиная с 1), <digit> – значение четной цифры.
  # При этом если в числе нет четных цифр, необходимо вывести следующий текст:
  # Четных цифр в числе нет
  # Примечание. Обратите внимание на то, что цифры в числе нужно рассматривать слева направо.
num = int(input())
n = len(str(num))
counter = 0
for i in range(1, n + 1):
    digit = (num // 10 ** (n - i)) % 10
    if digit % 2 == 0:
          counter += 1
          print(f"{counter}-я четная цифра равна {digit}", sep = "\n")
if counter == 0:
   print("Четных цифр в числе нет")
              
