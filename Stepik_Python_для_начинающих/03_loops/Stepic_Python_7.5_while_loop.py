  # Программа должна вывести «YES» (без кавычек), если последовательность его цифр при просмотре справа налево является упорядоченной по неубыванию, или «NO» (без кавычек) в противном случае.
num = int(input())
last_digit = num % 10
counter = 1
while num != 0:
    last_digit_2 = num % 10
    if last_digit_2 >= last_digit:
        counter *= 1
    elif last_digit_2 < last_digit:
        counter *= 0
    last_digit = last_digit_2
    num //= 10
if counter > 0:
    print("YES")
else:
    print("NO")         
    

