  # Задача №1 - Список чисел
  # На вход программе подаётся одно число n. Напишите программу, которая выводит список [1, 2, 3, ..., n].
num = int(input())
print(list(range(1, num + 1)))

  # Задача №2 - Список букв
  # На вход программе подаётся натуральное число n. Напишите программу, которая выводит список, состоящий из n букв английского алфавита ['a', 'b', 'c', ...] в нижнем регистре.
num = int(input())
total = ""
digit = ord('a') - 1
for i in range(1, num + 1):
    if 1 <= num <= 26:
        total += chr(digit + i)
    if num > 26:
        break
print(list(total))

  # Задача №3 - Список нечётных чисел
  # На вход программе подаётся число n(n≥1). Напишите программу, которая создаёт список из нечётных чисел от 1 до n (включительно) и выводит его.
num = int(input())
print(list(range(1, num + 1, 2)))

