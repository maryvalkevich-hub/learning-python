  # Задача №9 - k-ая буква слова
  # На вход программе подаются натуральное число n и n строк, а затем число k. Напишите программу, которая выводит k-ую букву из введённых строк на одной строке без пробелов.
  # Примечание. Если некоторые строки слишком короткие и в них нет символа с заданным номером, то такие строки при выводе нужно игнорировать.
n = int(input())
words = []
letters = "" 
for _ in range(n):
    words.append(input())
k = int(input())
for word in words:
    if len(word) >= k:
        letters += word[k - 1] 
print(letters)
