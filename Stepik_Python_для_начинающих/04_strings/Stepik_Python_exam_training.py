  # Задача №1 - Генератор хэштегов для ArtStation 🏷️
  # Ты написала текст для поста, но забыла добавить хэштеги. На вход подается строка из слов, разделенных пробелами (например, "шоколад яблоко студия").
  # Твоя задача: превратить каждое слово в хэштег и вывести их в одну строку через пробел.

text = input()
