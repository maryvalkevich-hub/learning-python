  # Задача №4 - Мини-шифр Цезаря 🕵️‍♀️
  # На вход подается строка текста.
  # Напиши программу, которая «сдвигает» каждый символ этой строки на 3 позиции вправо по таблице Unicode и выводит новую строку.
text = input()
new_text = ""
for i in range(len(text)):
    digit = ord(text[i]) + 3

    if digit < 97:
        digit += 26
    new_text += chr(digit)
print(new_text)  

  # Задача №5 -  Умный ценник 🏷️
  # На вход подается цена товара (дробное число) и процент скидки (целое число от 0 до 100). 
  # Рассчитай итоговую цену.
  # Если итоговая цена меньше 100, добавь в конец строки эмодзи 🔥, иначе добавь эмодзи 💎.
  # Выведи результат, отформатировав цену до 2 знаков после запятой.
  # Формат: Итоговая цена: {цена} {эмодзи}
a, b = float(input()), int(input())
c = round((a - ((a / 100) * b)), 2)
if c < 100:
    print(f"Итоговая цена: {c:.2f} 🔥")
else:
    print(f"Итоговая цена: {c:.2f} 💎")

  # Задача №6 - Цифровой детектив (Хардкор!)
