  # Ожидаемый вывод: хорошее яблочко
text = input()
new_text = ""       # пример для проверки - "хорооошееее яблочко" не подходит так как результат будет "хороше яблочко" так как там много букв е и 2 точно не получится оставить. Если примером будет "хооорошшииий карррандашшш", то все сработает как часы.
