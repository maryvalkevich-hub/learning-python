  # Твоя задача: найти сумму Unicode-кодов только тех символов, которые являются цифрами.
  # Важное условие: Метод .isdigit() использовать нельзя! Ты должна определить, является ли символ цифрой, исключительно через его код (вспомни диапазоны кодов для цифр в таблице Unicode).
  # Выведи одну цифру — полученную сумму.
text = input()
