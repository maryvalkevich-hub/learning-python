  # Задача №3 - Интересное число 🤔.Назовём число интересным, если в нём разность максимальной и минимальной цифры равняется средней по величине цифре. Напишите программу, которая определяет, интересное число или нет. Если число интересное, следует вывести текст «Число интересное» (без кавычек), иначе – «Число неинтересное» (без кавычек).
  # На вход программе подаётся натуральное трёхзначное число.
num = int(input())
digit1 = num // 10 ** 2
digit2 = (num // 10) % 10
digit3 = num % 10
a = max(digit1, digit2, digit3)
b = min(digit1, digit2, digit3)
c = abs(a - b)  # разность максимального и минимального
e = (digit1 + digit2 + digit3) - (a + b)  # средняя по величине цифра
if c == e:
    print("Число интересное")
else:
    print("Число неинтересное")

